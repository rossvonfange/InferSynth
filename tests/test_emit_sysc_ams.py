"""Tests for the SystemC-AMS emitter + kernel seam (WP-S2).

Covers: byte-stable golden emission for both op-amp cells, emission determinism,
the bundled AMS header matching the committed catalog artifact, design-level
structural emission with a loud stub gap, the toolchain probe (monkeypatched
present/absent), CSV parsing, the ``ams-simulation`` gate's two distinct loud
skips, and — under ``@pytest.mark.sysc_ams`` — the real compile+run+cross-check
against the v0 tier (skipped when no toolchain is present).
"""

