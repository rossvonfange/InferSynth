def test_toolchain_absent_when_no_headers(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(tc_mod.shutil, "which", lambda _c: "/usr/bin/g++")
    monkeypatch.setattr(tc_mod, "_find_header_dir", lambda *_a, **_k: None)
    tchain = detect_toolchain(env={})
    assert not tchain.available
    assert any("SystemC" in r for r in tchain.reasons)
    assert "not found" in tchain.why_unavailable()


def test_toolchain_absent_when_no_compiler(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(tc_mod.shutil, "which", lambda _c: None)
    monkeypatch.setattr(tc_mod, "_find_header_dir", lambda *_a, **_k: "/opt/sc")
    tchain = detect_toolchain(env={})
    assert not tchain.available
    assert any("compiler" in r for r in tchain.reasons)


def test_toolchain_present_when_all_found(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(tc_mod.shutil, "which", lambda _c: "/usr/bin/g++")
    monkeypatch.setattr(tc_mod, "_find_header_dir", lambda *_a, **_k: "/opt/sc")
    tchain = detect_toolchain(env={"SYSTEMC_HOME": "/opt/sc", "SYSTEMC_AMS_HOME": "/opt/sc"})
    assert tchain.available
    assert tchain.cxx == "/usr/bin/g++"
    assert tchain.why_unavailable() == "toolchain available"


def test_real_probe_runs_on_this_machine() -> None:
    # Not asserting a value — just that the real probe returns a well-formed result.
    tchain = detect_toolchain()
    assert isinstance(tchain, AmsToolchain)
    assert isinstance(tchain.available, bool)


