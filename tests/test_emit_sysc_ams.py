@pytest.mark.sysc_ams
@pytest.mark.skipif(
    not detect_toolchain().available, reason="SystemC-AMS toolchain not installed"
)
def test_ams_matches_v0_tier() -> None:  # pragma: no cover - needs toolchain
    from infersynth.gates.simulation import run_cell_simulation

    cell = load_cell(NONINV)
    ams = ams_simulation_cell_gate(cell)
    assert ams.status == GateStatus.PASS
    # Cross-validate: the v0 tier passes the same operating point.
    v0_rows = run_cell_simulation(cell)
    assert all(ok for _, ok, _ in v0_rows)
