# --------------------------------------------------------------------------- #
# Design-level structural emission.                                            #
# --------------------------------------------------------------------------- #
def _synthetic_design() -> Design:
    amp = Cell(
        "opamp-gain-noninverting",
        ports=[
            Port("IN", PortDirection.IN, PortKind.ELECTRICAL),
            Port("OUT", PortDirection.OUT, PortKind.ELECTRICAL),
            Port("VCC", PortDirection.IN, PortKind.POWER),
            Port("VEE", PortDirection.IN, PortKind.POWER),
            Port("GND", PortDirection.IN, PortKind.POWER),
        ],
        params=[Param("gain", "float")],
    )
    mystery = Cell(
        "mystery",
        ports=[
            Port("A", PortDirection.IN, PortKind.ELECTRICAL),
            Port("B", PortDirection.OUT, PortKind.ELECTRICAL),
        ],
    )
    d = Design(
        "demo",
        ports=[
            Port("IN_EXT", PortDirection.IN),
            Port("OUT_EXT", PortDirection.OUT),
            Port("VCC", PortDirection.IN, PortKind.POWER),
            Port("VEE", PortDirection.IN, PortKind.POWER),
            Port("GND", PortDirection.IN, PortKind.POWER),
            Port("SIN", PortDirection.IN),
            Port("SOUT", PortDirection.OUT),
        ],
    )
    d.add_instance("amp1", amp, {"gain": 10})
    d.add_instance("amp2", amp, {"gain": 4})
    d.add_instance("stub1", mystery)
    d.connect("vin", (BOUNDARY, "IN_EXT"), ("amp1", "IN"))
    d.connect("vmid", ("amp1", "OUT"), ("amp2", "IN"))
    d.connect("vout", ("amp2", "OUT"), (BOUNDARY, "OUT_EXT"))
    for r in ("VCC", "VEE", "GND"):
        d.connect(r.lower(), (BOUNDARY, r), ("amp1", r), ("amp2", r))
    d.connect("sin", (BOUNDARY, "SIN"), ("stub1", "A"))
    d.connect("sout", ("stub1", "B"), (BOUNDARY, "SOUT"))
    return d


def test_design_emission_wires_modeled_and_stubs_gap() -> None:
    el = elaborate(_synthetic_design())
    specs = {"opamp-gain-noninverting": spec_from_cell(load_cell(NONINV))}
    ed = emit_design(el, specs)

    top = ed.files["top.cpp"]
    # Both amps wired; the shared vmid net threads amp1.OUT into amp2.IN.
    assert "opamp_gain_noninverting amp1;" in top
    assert "opamp_gain_noninverting amp2;" in top
    assert "amp1.OUT(sig_net_vmid);" in top
    assert "amp2.IN(sig_net_vmid);" in top
    # One signal per net.
    assert "sig_net_vin" in top and "sig_net_vout" in top
    # The header is bundled for a hermetic build.
    assert "opamp-gain-noninverting.h" in ed.files

    # The gap is recorded and LOUD.
    assert not ed.report.complete
    assert [g[0] for g in ed.report.gaps] == ["stub1"]
    assert "!! STUB !!" in top
    rendered = ed.report.render()
    assert "STUBBED" in rendered
    assert "stub1" in rendered


def test_design_emission_is_deterministic() -> None:
    specs = {"opamp-gain-noninverting": spec_from_cell(load_cell(NONINV))}
    a = emit_design(elaborate(_synthetic_design()), specs)
    b = emit_design(elaborate(_synthetic_design()), specs)
    assert a.files == b.files


def test_design_all_modeled_reports_complete() -> None:
    # A design with only modeled instances has no gaps.
    amp = Cell(
        "opamp-gain-noninverting",
        ports=[
            Port("IN", PortDirection.IN, PortKind.ELECTRICAL),
            Port("OUT", PortDirection.OUT, PortKind.ELECTRICAL),
            Port("VCC", PortDirection.IN, PortKind.POWER),
            Port("VEE", PortDirection.IN, PortKind.POWER),
            Port("GND", PortDirection.IN, PortKind.POWER),
        ],
        params=[Param("gain", "float")],
    )
    d = Design(
        "solo",
        ports=[
            Port("I", PortDirection.IN),
            Port("O", PortDirection.OUT),
            Port("VCC", PortDirection.IN, PortKind.POWER),
            Port("VEE", PortDirection.IN, PortKind.POWER),
            Port("GND", PortDirection.IN, PortKind.POWER),
        ],
    )
    d.add_instance("a1", amp, {"gain": 2})
    d.connect("i", (BOUNDARY, "I"), ("a1", "IN"))
    d.connect("o", ("a1", "OUT"), (BOUNDARY, "O"))
    for r in ("VCC", "VEE", "GND"):
        d.connect(r.lower(), (BOUNDARY, r), ("a1", r))
    ed = emit_design(elaborate(d), {"opamp-gain-noninverting": spec_from_cell(load_cell(NONINV))})
    assert ed.report.complete
    assert "STUBBED" not in ed.report.render()


