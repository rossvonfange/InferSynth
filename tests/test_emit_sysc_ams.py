# --------------------------------------------------------------------------- #
# The ams-simulation gate: two distinct loud skips.                            #
# --------------------------------------------------------------------------- #
def test_gate_skips_loud_when_no_ams_model() -> None:
    result = ams_simulation_cell_gate(load_cell(DECOUPLING))
    assert result.status == GateStatus.SKIPPED
    assert result.gate == AMS_GATE
    assert "no model/ams/" in result.diagnostics[0]
    assert "falls back to the v0" in result.diagnostics[0]


def test_gate_skips_loud_when_toolchain_absent(monkeypatch: pytest.MonkeyPatch) -> None:
    # Cell has a model, but force the toolchain absent.
    monkeypatch.setattr(
        "infersynth.gates.ams_simulation.detect_toolchain",
        lambda: AmsToolchain(available=False, reasons=("SystemC-AMS headers not found",)),
    )
    result = ams_simulation_cell_gate(load_cell(NONINV))
    assert result.status == GateStatus.SKIPPED
    assert result.gate == AMS_GATE
    assert "toolchain absent" in result.diagnostics[0]
    assert "SystemC-AMS headers not found" in result.diagnostics[0]


def test_gate_skip_wordings_are_distinct() -> None:
    no_model = ams_simulation_cell_gate(load_cell(DECOUPLING)).diagnostics[0]
    # The real machine has no toolchain, so this is the toolchain-absent skip.
    with_model = ams_simulation_cell_gate(load_cell(NONINV))
    assert with_model.status == GateStatus.SKIPPED
    assert no_model != with_model.diagnostics[0]


