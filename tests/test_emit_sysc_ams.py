NONINV = CATALOG / "opamp-gain-noninverting"
X4 = CATALOG / "opamp-gain-x4-noninverting"
DECOUPLING = CATALOG / "decoupling"

_CELLS = ("opamp-gain-noninverting", "opamp-gain-x4-noninverting")


