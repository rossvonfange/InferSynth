@pytest.mark.parametrize("name", _CELLS)
def test_cell_main_cpp_matches_golden(name: str) -> None:
    cell = load_cell(CATALOG / name)
    emitted = emit_cell(cell)
    assert emitted is not None
    expected = (GOLDEN / name / "main.cpp").read_text()
    assert emitted.files["main.cpp"] == expected


@pytest.mark.parametrize("name", _CELLS)
def test_cell_makefile_matches_golden(name: str) -> None:
    cell = load_cell(CATALOG / name)
    emitted = emit_cell(cell)
    assert emitted is not None
    expected = (GOLDEN / name / "Makefile").read_text()
    assert emitted.files["Makefile"] == expected


@pytest.mark.parametrize("name", _CELLS)
def test_emission_is_deterministic(name: str) -> None:
    cell = load_cell(CATALOG / name)
    a = emit_cell(cell)
    b = emit_cell(cell)
    assert a is not None and b is not None
    assert a.files == b.files
    assert a.csv_columns == b.csv_columns


@pytest.mark.parametrize("name", _CELLS)
def test_bundled_header_matches_catalog(name: str) -> None:
    cell = load_cell(CATALOG / name)
    emitted = emit_cell(cell)
    assert emitted is not None
    catalog_header = (CATALOG / name / "model" / "ams" / f"{name}.h").read_text()
    assert emitted.files[f"{name}.h"] == catalog_header


def test_emit_cell_returns_none_without_ams_model() -> None:
    # A structural-only cell ships no model/ams/.
    assert emit_cell(load_cell(DECOUPLING)) is None
    assert spec_from_cell(load_cell(DECOUPLING)) is None


def test_no_timestamp_in_emitted_sources() -> None:
    import re

    emitted = emit_cell(load_cell(NONINV))
    assert emitted is not None
    blob = "\n".join(emitted.files.values())
    assert "generated at" not in blob.lower()
    # No ISO-8601-ish date/time anywhere (emission is a pure function).
    assert not re.search(r"\d{4}-\d{2}-\d{2}", blob)


def test_columns_and_checks_shape() -> None:
    emitted = emit_cell(load_cell(NONINV))
    assert emitted is not None
    assert emitted.csv_columns == ("t", "IN", "OUT")
    names = [c.name for c in emitted.checks]
    assert "amplitude_ratio(IN->OUT)" in names
    assert "clipped_within(OUT)" in names

    x4 = emit_cell(load_cell(X4))
    assert x4 is not None
    assert x4.csv_columns == ("t", "IN1", "IN2", "IN3", "IN4", "OUT1", "OUT2", "OUT3", "OUT4")
    x4names = [c.name for c in x4.checks]
    for k in (1, 2, 3, 4):
        assert f"amplitude_ratio(IN{k}->OUT{k})" in x4names


